#!/usr/bin/env python3
"""Section 4.5 / Appendix G: receptive-field similarity and clustering NMI of default voltage-STDP
(MNIST, full scaffold, seeds 0-4) at 5,000, 10,000, 20,000 and 60,000 training images.

Inputs: experiments/runs/<run>/metrics.json, fields "mean_cosine_similarity" (mean pairwise cosine
similarity of the 400 receptive fields) and "nmi" (normalised mutual information between the labels
and the partition of the test images by winning neuron), both written by experiments/scripts/run_single.py.
Runs (the networks of scripts/score/section45_probefix_mnist.py):
  5k/10k/20k: voltage_S_full_N400_seed{s}_flen{5k,10k,20k};
  60k: voltage_S_full_N400_seed0__b_fix_tc1e4_60k and voltage_S_full_N400_seed{s}__b_fix_tc1e4 (s >= 1).
Mean and sample s.d. (ddof=1) over seeds.
Usage (repo root): PYTHONPATH=. python scripts/score/section45_cosine_nmi.py [--runs DIR]
Out: results/section45_cosine_nmi.json, results/section45_cosine_nmi.md
"""
import argparse
import json
import os

import numpy as np

OUT = "results/section45_cosine_nmi"
SEEDS = (0, 1, 2, 3, 4)


def run_name(n, s):
    if n == 60000:
        return "voltage_S_full_N400_seed0__b_fix_tc1e4_60k" if s == 0 else f"voltage_S_full_N400_seed{s}__b_fix_tc1e4"
    return f"voltage_S_full_N400_seed{s}_flen{n // 1000}k"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="experiments/runs")
    args = ap.parse_args()
    out = dict(seeds=list(SEEDS), rows=[])
    for n in (5000, 10000, 20000, 60000):
        m = [json.load(open(os.path.join(args.runs, run_name(n, s), "metrics.json"))) for s in SEEDS]
        row = dict(n_train=n)
        for k in ("mean_cosine_similarity", "nmi"):
            v = [float(x[k]) for x in m]
            row[k] = v
            row[k + "_mean_sd"] = (float(np.mean(v)), float(np.std(v, ddof=1)))
        out["rows"].append(row)
    json.dump(out, open(OUT + ".json", "w"), indent=1)
    L = ["# Voltage-STDP receptive-field similarity and clustering NMI (MNIST, full scaffold)", "",
         "Generated by `scripts/score/section45_cosine_nmi.py` from each run's metrics.json "
         f"(seeds {SEEDS[0]}-{SEEDS[-1]}; mean ± s.d.).", "",
         "| training images | mean pairwise cosine | NMI |", "|--:|--:|--:|"]
    for r in out["rows"]:
        c, z = r["mean_cosine_similarity_mean_sd"], r["nmi_mean_sd"]
        L.append(f"| {r['n_train']:,} | {c[0]:.3f} ± {c[1]:.3f} | {z[0]:.3f} ± {z[1]:.3f} |")
    open(OUT + ".md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
