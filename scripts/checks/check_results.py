# Files whose bytes are pinned elsewhere and therefore keep the script path they were written with:
# grid.json's sha256 is recorded in every Clopath-port run's meta.json (grid_sha256), so it still names
# the pre-release location of its generator. Compared after mapping that path to the current one.
PINNED_RENAMES = {
    "results/clopath_port_calibration/grid.json": [("scripts/clopath_port_select_grid.py",
                                                     "scripts/train/clopath_port_select_grid.py")],
}


def json_diffs(a, b, path="$", skip=frozenset(), out=None):
    """All differences between two JSON values: [(path, shipped, new)]."""
    out = [] if out is None else out
    if path in skip:
        return out
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            out.append((path, f"keys only shipped {sorted(set(a) - set(b))[:5]}",
                        f"keys only new {sorted(set(b) - set(a))[:5]}"))
        for k in a:
            if k in b:
                json_diffs(a[k], b[k], f"{path}.{k}", skip, out)
        return out
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            out.append((path, f"length {len(a)}", f"length {len(b)}"))
        for i, (x, y) in enumerate(zip(a, b)):
            json_diffs(x, y, f"{path}[{i}]", skip, out)
        return out
    num = (int, float)
    if isinstance(a, num) and isinstance(b, num) and not isinstance(a, bool) and not isinstance(b, bool):
        if (isinstance(a, float) and math.isnan(a)) and (isinstance(b, float) and math.isnan(b)):
            return out
        if not (a == b or abs(a - b) <= 1e-9 or abs(a - b) <= 1e-9 * max(abs(a), abs(b))):
            out.append((path, a, b))
        return out
    if a != b:
        out.append((path, a, b))
    return out


def _short(v):
    return repr(v) if isinstance(v, (int, float)) else repr(str(v)[:60])


def compare(rel, shipped, new):
    """None if equal, else a one-line reason."""
    if not new.exists():
        return "not written"
    if shipped.suffix == ".json":
        try:
            a, b = json.loads(shipped.read_text()), json.loads(new.read_text())
        except ValueError as e:
            return f"invalid JSON: {e}"
        if rel in PINNED_RENAMES:
            txt = json.dumps(a)
            for old, cur in PINNED_RENAMES[rel]:
                txt = txt.replace(old, cur)
            a = json.loads(txt)
        d = json_diffs(a, b, skip=VOLATILE.get(rel, frozenset()))
        if not d:
            return None
        nums = [abs(x - y) for _, x, y in d if isinstance(x, (int, float)) and isinstance(y, (int, float))]
        p, x, y = d[0]
        return (f"{len(d)} differences ({len(nums)} numeric, max |diff| {max(nums):.4g}); first {p}: "
                f"{_short(x)} vs {_short(y)}" if nums else f"{len(d)} differences; first {p}: {_short(x)} vs {_short(y)}")
    if shipped.read_bytes() == new.read_bytes():
        return None
    a, b = shipped.read_text(errors="replace").splitlines(), new.read_text(errors="replace").splitlines()
    bad = [i for i, (x, y) in enumerate(zip(a, b)) if x != y]
    if bad:
        i = bad[0]
        return (f"{len(bad)} lines differ{'' if len(a) == len(b) else f' ({len(a)} vs {len(b)} lines)'}; "
                f"first line {i + 1}: shipped {a[i][:90]!r} / new {b[i][:90]!r}")
    return f"{len(a)} vs {len(b)} lines"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--only", nargs="+", choices=sorted(TASKS), help="these tables (+ their dependencies)")
    ap.add_argument("--figures", metavar="REF_DIR", help="also regenerate the figures, compare PDFs with REF_DIR")
    ap.add_argument("--no-tables", action="store_true", help="figures only")
    ap.add_argument("--jobs", type=int, default=3, help="scorers run in parallel")
    ap.add_argument("--keep", action="store_true", help="keep the scratch folder")
    ap.add_argument("--workspace", metavar="DIR", help="use DIR as the scratch folder (kept); survives reboots")
    ap.add_argument("--resume", action="store_true",
                    help="with --workspace: do not rerun scorers that already finished there (marker _logs/<name>.done)")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    if args.list:
        for n, (c, o, d) in TASKS.items():
            print(f"{n:32s} {' '.join(c):70s} -> {', '.join(o)}")
        for n, (c, s) in FIGURES.items():
            print(f"{n:32s} {' '.join(c):70s} -> {', '.join(s)} (figures)")
        return 0
    if args.workspace:
        ws = Path(args.workspace).resolve(); ws.mkdir(parents=True, exist_ok=True); args.keep = True
    else:
        ws = Path(tempfile.mkdtemp(prefix="check_results_"))
    print(f"scratch folder: {ws}")
    if not (ws / ".built").exists():
        build_workspace(ws)
        (ws / ".built").touch()
    logs = ws / "_logs"
    logs.mkdir(exist_ok=True)
    finished = lambda n: args.resume and (logs / f"{n}.done").exists()
    rows, failed = [], False

    names = [] if args.no_tables else order(args.only or list(TASKS))
    for n in [n for n in names if n in STALE]:
        names.remove(n)
        for o in TASKS[n][1]:
            rows.append((o, n, "STALE", STALE[n], 0.0))
    for n in names:                                   # delete outputs first: nothing stale is read
        if finished(n):
            continue
        for o in TASKS[n][1]:
            (ws / o).unlink(missing_ok=True)
    done, status = set(), {}

    def task(n):
        cmd, outs, deps = TASKS[n]
        bad = [d for d in deps if status.get(d) != "ok" and d in names]
        if bad:
            return n, None, 0.0, f"dependency failed: {', '.join(bad)}"
        if finished(n):
            print(f"[{time.strftime('%H:%M:%S')}] {n}: finished in an earlier run, not rerun", flush=True)
            return n, 0, 0.0, None
        rc, dt = run(cmd, ws, logs / f"{n}.log")
        if rc is not None and rc < 0:                 # killed by a signal (seen: rare SIGSEGV under heavy load)
            print(f"[{time.strftime('%H:%M:%S')}] {n}: signal {-rc}, running it once more", flush=True)
            os.replace(logs / f"{n}.log", logs / f"{n}.signal{-rc}.log")
            rc, dt2 = run(cmd, ws, logs / f"{n}.log")
            dt += dt2
        if rc == 0:
            (logs / f"{n}.done").touch()
        return n, rc, dt, None

    pending = list(names)
    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as ex:
        futs = {}
        while pending or futs:
            for n in list(pending):
                if all(d in done or d not in names for d in TASKS[n][2]):
                    pending.remove(n)
                    futs[ex.submit(task, n)] = n
            if not futs:
                break
            f = next(iter(_wait_any(futs)))
            n, rc, dt, err = f.result()
            del futs[f]
            done.add(n)
            status[n] = "ok" if (rc == 0 and err is None) else "fail"
            for o in TASKS[n][1]:
                if err:
                    why = err
                elif rc != 0:
                    tail = (logs / f"{n}.log").read_text(errors="replace").strip().splitlines()[-1:]
                    why = f"exit {rc}: {tail[0][:150] if tail else ''}"
                else:
                    why = compare(o, REPO / o, ws / o)
                rows.append((o, n, "PASS" if why is None else "FAIL", why or "", dt))
                failed |= why is not None
            print(f"[{time.strftime('%H:%M:%S')}] {n}: {status[n]} ({dt:.0f} s)", flush=True)

    if args.figures:
        ref = Path(args.figures)
        figdir = ws / "_figures"
        figdir.mkdir()
        for n, (cmd, stems) in FIGURES.items():
            if n == "make_section44_mechanism_figure" and not os.environ.get("CLOPATH_MODELDB_DIR"):
                for s in stems:
                    rows.append((f"{s}.pdf", n, "SKIP", "CLOPATH_MODELDB_DIR not set", 0.0))
                continue
            rc, dt = run(cmd, ws, logs / f"fig_{n}.log", {"FIG_OUT_DIR": str(figdir)})
            for s in stems:
                new, old = figdir / f"{s}.pdf", ref / f"{s}.pdf"
                if rc != 0:
                    why = f"exit {rc} (log {logs / f'fig_{n}.log'})"
                elif not new.exists():
                    why = "not written"
                elif not old.exists():
                    why = f"no reference {old}"
                else:
                    why = None if new.read_bytes() == old.read_bytes() else "PDF bytes differ"
                rows.append((f"{s}.pdf", n, "PASS" if why is None else "FAIL", why or "", dt))
                failed |= why is not None

    print()
    w = max([len(r[0]) for r in rows] + [10])
    for o, n, st, why, dt in rows:
        print(f"{st:5s}  {o:{w}s}  {n:32s} {why}")
    print(f"\n{sum(r[2] == 'PASS' for r in rows)} PASS, {sum(r[2] == 'FAIL' for r in rows)} FAIL, "
          f"{sum(r[2] == 'SKIP' for r in rows)} SKIP, {sum(r[2] == 'STALE' for r in rows)} STALE; logs in {logs}")
    if args.keep or failed:
        print(f"scratch folder kept: {ws}")
    else:
        shutil.rmtree(ws)
    return 1 if failed else 0


def _wait_any(futs):
    from concurrent.futures import FIRST_COMPLETED, wait
    d, _ = wait(list(futs), return_when=FIRST_COMPLETED)
    return d


if __name__ == "__main__":
    sys.exit(main())
