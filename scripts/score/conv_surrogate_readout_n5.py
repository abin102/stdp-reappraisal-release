#!/usr/bin/env python3
"""Surrogate-gradient readout on the two-layer convolutional voltage-STDP network, five seeds
(Section 4.3, Appendix I): trained vs random (untrained) filters.

Inputs: the readout logs of conv/conv2layer_voltage_stdp.py, one per network:
  trained filters: trainedreadout_seed{1..4}.log and paper_seed5.log (seed 5);
  random filters:  randomfilters_seed{1..5}.log.
Each log has 75 lines "Epoch e/75 | ... | Test: x% | Best: y% | ..." from one readout training.
Reported: the best test accuracy over the 75 epochs (the "Best" of the last epoch line, as the paper
reports) and the test accuracy of the final epoch. The logs print one decimal.
Gap = trained - random of the same seed; mean and sample s.d. (ddof=1) over seeds.
Usage (repo root): PYTHONPATH=. python scripts/score/conv_surrogate_readout_n5.py [--log_dir DIR]
Out: results/conv_surrogate_readout_n5.json, results/conv_surrogate_readout_n5.md
"""
import argparse
import json
import os
import re

import numpy as np

OUT = "results/conv_surrogate_readout_n5"
SEEDS = (1, 2, 3, 4, 5)
EPOCH = re.compile(r"Epoch +(\d+)/(\d+) \|.*\| Test: ([\d.]+)% \| Best: ([\d.]+)%")


def log_name(kind, s):
    if kind == "trained":
        return "paper_seed5.log" if s == 5 else f"trainedreadout_seed{s}.log"
    return f"randomfilters_seed{s}.log"


def read_log(path):
    ep = [m.groups() for m in map(EPOCH.search, open(path, errors="replace")) if m]
    if not ep:
        raise SystemExit(f"no epoch lines in {path}")
    e, n = int(ep[-1][0]), int(ep[-1][1])
    if e != n or len(ep) != n:
        raise SystemExit(f"{path}: {len(ep)} epoch lines, last {e}/{n} (expected one complete readout)")
    test = [float(x[2]) for x in ep]
    best = float(ep[-1][3])
    assert abs(best - max(test)) < 1e-9, path
    return dict(epochs=n, best=best, final=test[-1])


def ms(x):
    return float(np.mean(x)), float(np.std(x, ddof=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--log_dir", default="results/logs_conv5",
                    help="folder with the readout logs (not shipped; written by the conv runs)")
    args = ap.parse_args()
    if not os.path.isdir(args.log_dir):
        raise SystemExit(f"log folder not found: {args.log_dir} (pass --log_dir)")
    R = {k: [read_log(os.path.join(args.log_dir, log_name(k, s))) for s in SEEDS] for k in ("trained", "random")}
    out = dict(seeds=list(SEEDS), log_dir=os.path.basename(os.path.normpath(args.log_dir)))
    for m in ("best", "final"):
        t, r = [x[m] for x in R["trained"]], [x[m] for x in R["random"]]
        g = [a - b for a, b in zip(t, r)]
        out[m] = dict(trained=t, random=r, gap=g, trained_mean_sd=ms(t), random_mean_sd=ms(r), gap_mean_sd=ms(g),
                      trained_below_random=int(sum(x < 0 for x in g)))
    json.dump(out, open(OUT + ".json", "w"), indent=1)
    f = lambda m: f"{m[0]:.1f} ± {m[1]:.1f}"
    L = ["# Surrogate-gradient readout on the convolutional network, five seeds", "",
         "Generated by `scripts/score/conv_surrogate_readout_n5.py` from the readout logs "
         "(best = best test accuracy over the 75 epochs; final = epoch 75).", "",
         "| seed | trained best | random best | trained final | random final |", "|--:|--:|--:|--:|--:|"]
    L += [f"| {s} | {out['best']['trained'][i]:.1f} | {out['best']['random'][i]:.1f} | "
          f"{out['final']['trained'][i]:.1f} | {out['final']['random'][i]:.1f} |" for i, s in enumerate(SEEDS)]
    L += [f"| mean ± s.d. | {f(out['best']['trained_mean_sd'])} | {f(out['best']['random_mean_sd'])} | "
          f"{f(out['final']['trained_mean_sd'])} | {f(out['final']['random_mean_sd'])} |", ""]
    for m in ("best", "final"):
        L.append(f"{m}: gap {f(out[m]['gap_mean_sd'])}, trained below random in "
                 f"{out[m]['trained_below_random']} of {len(SEEDS)} seeds.")
    open(OUT + ".md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
