#!/usr/bin/env python3
"""Appendix I (Fisher ratio vs filter similarity) on the probe-fix matrix networks (CPU only).

Networks: {pair_exp,triplet,voltage}_S_full_N400_seed{0-4}[_{dataset}]_probefix_trained, the trained
networks of Section 4.7 (10,000 training images), on the six datasets of the original Appendix I
analysis (scripts/tier1_readout_unsupervised_analysis.py): MNIST, N-MNIST, EMNIST-Letters,
Fashion-MNIST, OrganAMNIST, BloodMNIST.
Per network:
  * Fisher ratio J = tr(between-class scatter) / tr(within-class scatter) of the test spike counts
    (same definition and data split as the original analysis: full test set);
  * mean pairwise cosine similarity of the receptive fields (metrics.json, as before);
  * linear-probe accuracy from results/probefix_matrix_n5.json (single probe).
Per dataset: does the Fisher ratio order the three rules as the accuracy does?

Outputs: results/appendix_i_probefix.json, results/appendix_i_probefix.md
Usage (repo root): python scripts/score/appendix_i_probefix.py
"""
import json
from pathlib import Path
import numpy as np

R = Path("experiments/runs")
RULES = [("pair_exp", "pair-STDP"), ("triplet", "triplet-STDP"), ("voltage", "voltage-STDP")]
DS = [("mnist", "MNIST"), ("nmnist", "N-MNIST"), ("emnist_letters", "EMNIST-Letters"),
      ("fmnist", "Fashion-MNIST"), ("organamnist", "OrganAMNIST"), ("bloodmnist", "BloodMNIST")]
ACC = {(r["rule"], r["dataset"], r["seed"]): r["linear"]
       for r in json.load(open("results/probefix_matrix_n5.json"))["runs"] if r["mode"] == "trained"}


def fisher_ratio(X, y):
    mu = X.mean(0); sb = sw = 0.0
    for c in np.unique(y):
        xc = X[y == c]
        if len(xc) < 2:
            continue
        m = xc.mean(0)
        sb += len(xc) * np.sum((m - mu) ** 2)
        sw += np.sum((xc - m) ** 2)
    return float(sb / max(sw, 1e-9))


def run_dir(rule, ds, s):
    return R / f"{rule}_S_full_N400_seed{s}{'' if ds == 'mnist' else '_' + ds}_probefix_trained"


def main():
    out = {}
    for ds, _ in DS:
        for rule, _ in RULES:
            fj, cs, ac = [], [], []
            for s in range(5):
                d = run_dir(rule, ds, s)
                z = np.load(d / "test_spike_counts.npz")
                fj.append(fisher_ratio(z["test_spike_counts"].astype(np.float64), z["test_labels"]))
                cs.append(float(json.load(open(d / "metrics.json"))["mean_cosine_similarity"]))
                ac.append(ACC[(rule, ds, s)])
            out[f"{rule}|{ds}"] = {k: [float(np.mean(v)), float(np.std(v, ddof=1))] for k, v in
                                   (("fisher", fj), ("cos_sim", cs), ("accuracy", ac))}
    json.dump(out, open("results/appendix_i_probefix.json", "w"), indent=1)
    L = ["# Appendix I on the probe-fix matrix networks (5 seeds, 10,000 training images)", "",
         "Generated by `scripts/score/appendix_i_probefix.py`. Fisher ratio of the test spike counts, mean filter",
         "cosine similarity, linear-probe accuracy (mean ± s.d.). Last column: does the Fisher ratio order",
         "the three rules as the accuracy does?", "",
         "| dataset | rule | Fisher ratio | cosine similarity | accuracy (%) | same order |", "|---|---|--:|--:|--:|:-:|"]
    for ds, dl in DS:
        f = [out[f"{r}|{ds}"]["fisher"][0] for r, _ in RULES]
        a = [out[f"{r}|{ds}"]["accuracy"][0] for r, _ in RULES]
        same = list(np.argsort(f)) == list(np.argsort(a))
        for (r, rl) in RULES:
            c = out[f"{r}|{ds}"]
            L.append(f"| {dl} | {rl} | {c['fisher'][0]:.3f} ± {c['fisher'][1]:.3f} | {c['cos_sim'][0]:.2f} | "
                     f"{c['accuracy'][0]:.1f} ± {c['accuracy'][1]:.1f} | {'yes' if same else 'NO'} |")
    open("results/appendix_i_probefix.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
