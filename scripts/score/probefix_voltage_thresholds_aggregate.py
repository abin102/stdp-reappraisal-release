#!/usr/bin/env python3
"""Aggregate the voltage-STDP threshold / spike-plateau add-on (scripts/train/probefix_voltage_thresholds_n5.sh).

Train-fit probe, as in scripts/score/probefix_aggregate.py: multinomial logistic regression, L2, C = 1,
fitted on the frozen spike counts of the 10,000 training images and scored on the full test set.
Each setting is compared, seed by seed, with the voltage-STDP MNIST random network of the
probe-fix matrix (voltage_S_full_N400_seed{s}_probefix_frozen); the thresholds and the plateau
act only inside the plasticity rule, so that network is the random baseline of every setting.
The reference row is voltage_S_full_N400_seed{s}_probefix_trained (published thresholds).

Outputs: results/probefix_voltage_thresholds_n5.{json,md}
Usage (repo root): python scripts/score/probefix_voltage_thresholds_aggregate.py [--allow-missing]
"""
import argparse, json, sys, warnings
from pathlib import Path
import numpy as np
from joblib import Parallel, delayed
from scripts.score._blas import fixed_threads
from sklearn.linear_model import LogisticRegression

warnings.filterwarnings("ignore")
R = Path("experiments/runs")
SEEDS = range(5)
SETTINGS = [  # label, description (theta- / theta+ in mV)
    ("trained", "reference: theta- = -70.6, theta+ = -45.3 (Clopath's values)"),
    ("thltd_m68", "theta- = -68"), ("thltd_m65", "theta- = -65 (our resting potential)"),
    ("thltd_m62", "theta- = -62"), ("thltd_m60", "theta- = -60"), ("thltd_m58", "theta- = -58"),
    ("thltd_m55", "theta- = -55"), ("thltd_m50", "theta- = -50"),
    ("thltp_m52", "theta+ = -52 (firing threshold), theta- = -70.6"),
    ("thltd_m65_thltp_m52", "theta+ = -52 and theta- = -65 (Table 3 row 4)"),
    ("plateau", "Clopath's 2-ms spike plateau (Table 3 row 5)"),
    ("frozen", "STDP disabled (random)"),
]


def score(label, seed):
    d = R / f"voltage_S_full_N400_seed{seed}_probefix_{label}"
    if not ((d / "completed.flag").exists() and (d / "train_spike_counts.npz").exists()
            and (d / "test_spike_counts.npz").exists()):
        return dict(label=label, seed=seed, run=d.name, complete=False)
    zt, ze = np.load(d / "train_spike_counts.npz"), np.load(d / "test_spike_counts.npz")
    Xtr, ytr = zt["train_spike_counts"].astype(np.float64), zt["train_labels"]
    Xte, yte = ze["test_spike_counts"].astype(np.float64), ze["test_labels"]
    acc = 100.0 * LogisticRegression(max_iter=100000, C=1.0).fit(Xtr, ytr).score(Xte, yte)  # as probefix_aggregate.py
    return dict(label=label, seed=seed, run=d.name, complete=True, n_train=int(len(ytr)),
                n_test=int(len(yte)), linear=float(acc), spikes_test=float(Xte.sum(1).mean()))


def ms(a):
    a = np.asarray(a, float)
    return (float(a.mean()), float(a.std(ddof=1)) if len(a) > 1 else 0.0) if len(a) else (np.nan, np.nan)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-missing", action="store_true")
    args = ap.parse_args()
    res = Parallel(n_jobs=12)(delayed(fixed_threads(score, 1))(l, s) for l, _ in SETTINGS for s in SEEDS)
    missing = [x["run"] for x in res if not x["complete"]]
    if missing and not args.allow_missing:
        sys.exit(f"ERROR: {len(missing)} of {len(res)} runs incomplete, e.g. {missing[:3]}. "
                 "Wait for the launchers, or pass --allow-missing.")
    by = {(x["label"], x["seed"]): x for x in res if x["complete"]}
    rows = {}
    for l, desc in SETTINGS:
        seeds = [s for s in SEEDS if (l, s) in by and ("frozen", s) in by]
        acc = [by[(l, s)]["linear"] for s in seeds]
        rows[l] = dict(description=desc, n=len(seeds), seeds=seeds, accuracy=ms(acc),
                       delta=ms([by[(l, s)]["linear"] - by[("frozen", s)]["linear"] for s in seeds]),
                       spikes_test=ms([by[(l, s)]["spikes_test"] for s in seeds]))
    json.dump(dict(protocol=__doc__.split("Outputs")[0].strip(), runs=res, settings=rows),
              open("results/probefix_voltage_thresholds_n5.json", "w"), indent=1)

    f = lambda t, p=1: "—" if np.isnan(t[0]) else f"{t[0]:.{p}f} ± {t[1]:.{p}f}"
    L = ["# Voltage-STDP threshold and spike-plateau settings, train-fit probe (5 seeds)", "",
         "Generated by `scripts/score/probefix_voltage_thresholds_aggregate.py`. MNIST, tuned voltage-STDP",
         "network, STDP on 10,000 training images; probe fitted on those images (frozen weights) and",
         "scored on the full 10,000-image test set. Δ = trained − random per seed (random = the same",
         "network with STDP disabled, shared by every setting). Mean ± s.d. over seeds.", ""]
    if missing:
        L += [f"**Incomplete: {len(missing)} of {len(res)} runs missing.**", ""]
    L += ["| setting | n | accuracy (%) | Δ vs random (points) | spikes per test image |",
          "|---|--:|--:|--:|--:|"]
    for l, _ in SETTINGS:
        r = rows[l]
        L.append(f"| {r['description']} | {r['n']} | {f(r['accuracy'])} | "
                 f"{'' if l == 'frozen' else f(r['delta'])} | {f(r['spikes_test'], 0)} |")
    if missing:
        L += ["", "Missing:", ""] + [f"- `{m}`" for m in missing]
    open("results/probefix_voltage_thresholds_n5.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
