#!/usr/bin/env python3
"""Appendix G (voltage-STDP across training lengths) under the single linear probe, seeds 0-4.

Sources (all scored with the single probe: fit on 10,000 training images, full test set):
  * re-extracted networks: results/reextract_probefix_scores.json ("new");
  * 10,000-image tuned networks: the probe-fix matrix (results/probefix_matrix_n5.json, voltage,
    trained), same tuned configuration and seeds as the vb3_trained runs used before
    (scripts/voltage_horizon_curve.py), which were not re-extracted.
Scaffolds (default configuration, MNIST): runs in SCAF; S_full 20k = flen20k, 60k = scaffold matrix.
Datasets (tuned configuration): 2k vhz2000, 5k vhz5000, 10k matrix, 60k as in
scripts/voltage_horizon_curve.py dirs_for().

Outputs: results/appendix_g_probefix.json, results/appendix_g_probefix.md
Usage (repo root): python scripts/score/appendix_g_probefix.py
"""
import json
import numpy as np

RE = {r["run"]: r["new"] for r in json.load(open("results/reextract_probefix_scores.json"))["runs"]}
MX = {(r["dataset"], r["seed"]): r["linear"] for r in json.load(open("results/probefix_matrix_n5.json"))["runs"]
      if r["rule"] == "voltage" and r["mode"] == "trained"}
SEEDS = (0, 1, 2, 3, 4)
V = "voltage_S_{sc}_N400_seed{s}"
SCAF = {  # scaffold -> {length: run-name template}
    "S_full": {5000: "voltage_S_full_N400_seed{s}_peak5k", 20000: "voltage_S_full_N400_seed{s}_flen20k",
               60000: None},
    "S_inh": {5000: "voltage_S_inh_only_N400_seed{s}_peak5k", 20000: "voltage_S_inh_only_N400_seed{s}_mid20k",
              60000: "voltage_S_inh_only_N400_seed{s}__b_fix_tc1e4"},
    "S_none": {5000: "voltage_S_none_N400_seed{s}_peak5k", 20000: "voltage_S_none_N400_seed{s}_mid20k",
               60000: "voltage_S_none_N400_seed{s}__b_fix_tc1e4"},
    "S_thr": {5000: "voltage_S_thr_only_N400_seed{s}_peak5k", 20000: "voltage_S_thr_only_N400_seed{s}_mid20k",
              60000: "voltage_S_thr_only_N400_seed{s}__b_fix_tc1e4"},
}
DS = ["mnist", "nmnist", "emnist_letters", "fmnist", "organamnist", "bloodmnist"]
NAME = {"mnist": "MNIST", "nmnist": "N-MNIST", "emnist_letters": "EMNIST-Letters", "fmnist": "Fashion-MNIST",
        "organamnist": "OrganAMNIST", "bloodmnist": "BloodMNIST"}


def s_full_60k(s):
    return "voltage_S_full_N400_seed0__b_fix_tc1e4_60k" if s == 0 else f"voltage_S_full_N400_seed{s}__b_fix_tc1e4"


def tag(ds):
    return "" if ds == "mnist" else f"_{ds}"


def ds_run(ds, h, s):
    if h in (2000, 5000):
        return f"voltage_S_full_N400_seed{s}{tag(ds)}_vhz{h}"
    for c in (f"voltage_S_full_N400_seed{s}_{ds}_vhz60000", f"voltage_S_full_N400_seed{s}_{ds}_{ds}_vhz60000",
              f"voltage_S_full_N400_seed{s}{tag(ds)}__nmnist_n5", f"voltage_S_full_N400_seed{s}{tag(ds)}__f3_fmnist_voltage_tuned",
              f"voltage_S_full_N400_seed0{tag(ds)}__{ds.split('mnist')[0]}_smoke_tuned" if s == 0 else None,
              f"voltage_S_full_N400_seed{s}{tag(ds)}__n5_{ds.split('mnist')[0]}_tuned"):
        if c and c in RE:
            return c
    raise KeyError((ds, h, s))


def ms(v):
    return [float(np.mean(v)), float(np.std(v, ddof=1)), len(v)]


def main():
    out = {"scaffolds": {}, "datasets": {}}
    for sc, hs in SCAF.items():
        out["scaffolds"][sc] = {}
        for h, t in hs.items():
            runs = [s_full_60k(s) if t is None else t.format(s=s) for s in SEEDS]
            out["scaffolds"][sc][h] = {"runs": runs, "acc": ms([RE[r] for r in runs])}
    for ds in DS:
        out["datasets"][ds] = {}
        for h in (2000, 5000, 10000, 60000):
            if h == 10000:
                v = [MX[(ds, s)] for s in SEEDS]; runs = [f"probe-fix matrix voltage {ds} seed {s}" for s in SEEDS]
            else:
                runs = [ds_run(ds, h, s) for s in SEEDS]; v = [RE[r] for r in runs]
            out["datasets"][ds][h] = {"runs": runs, "acc": ms(v)}
    json.dump(out, open("results/appendix_g_probefix.json", "w"), indent=1)
    f = lambda c: f"{c['acc'][0]:.1f} ± {c['acc'][1]:.1f}"
    L = ["# Appendix G under the single linear probe (seeds 0-4)", "",
         "Generated by `scripts/score/appendix_g_probefix.py`. Accuracy %, mean ± s.d. over seeds 0-4.", "",
         "## Default configuration, MNIST, by scaffold", "", "| scaffold | 5,000 | 20,000 | 60,000 | 60k - 5k |", "|---|--:|--:|--:|--:|"]
    for sc, c in out["scaffolds"].items():
        L.append(f"| {sc} | {f(c[5000])} | {f(c[20000])} | {f(c[60000])} | {c[60000]['acc'][0] - c[5000]['acc'][0]:+.1f} |")
    L += ["", "## Tuned configuration, by dataset (10,000 = probe-fix matrix networks)", "",
          "| dataset | 2,000 | 5,000 | 10,000 | 60,000 | final - peak | falls at every step |", "|---|--:|--:|--:|--:|--:|:-:|"]
    for ds, c in out["datasets"].items():
        m = [c[h]["acc"][0] for h in (2000, 5000, 10000, 60000)]
        mono = all(b < a for a, b in zip(m, m[1:]))
        L.append(f"| {NAME[ds]} | " + " | ".join(f(c[h]) for h in (2000, 5000, 10000, 60000))
                 + f" | {m[-1] - max(m):+.1f} | {'yes' if mono else 'no'} |")
    open("results/appendix_g_probefix.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
