#!/usr/bin/env python3
"""Data for the rebuilt Table 2 (input decomposition) under the paper's single linear probe.

Combines results/input_baselines_probefix.json (encoded spike input and raw pixels; first 10,000
training images of each seed's order, full test set, seeds 0-4) with results/probefix_matrix_n5.json
(the 240 probe-fix runs: STDP on 10,000 training images, same probe). Every value is mean +- s.d.
over seeds 0-4; differences from the encoded input are computed per seed (same seed = same
10,000 training images), then averaged. "same sign" = the difference has the same sign in all 5 seeds.

Outputs: results/table2_probefix.md, results/table2_probefix.json
Usage (repo root): python scripts/score/table2_probefix.py
"""
import json
import numpy as np

DS = [("mnist", "MNIST"), ("nmnist", "N-MNIST"), ("emnist_letters", "EMNIST-Letters"),
      ("fmnist", "Fashion-MNIST"), ("organamnist", "OrganAMNIST"), ("bloodmnist", "BloodMNIST"),
      ("tissuemnist", "TissueMNIST"), ("pathmnist", "PathMNIST")]
RULES = [("pair_exp", "pair"), ("triplet", "triplet"), ("voltage", "voltage")]
SEEDS = range(5)


def main():
    b = json.load(open("results/input_baselines_probefix.json"))
    m = json.load(open("results/probefix_matrix_n5.json"))
    run = {(r["rule"], r["dataset"], r["seed"], r["mode"]): r["linear"] for r in m["runs"] if r.get("complete")}
    ms = lambda a: (float(np.mean(a)), float(np.std(a, ddof=1)))
    f = lambda t: f"{t[0]:.1f} ± {t[1]:.1f}"
    out, L = {}, ["# Table 2 data: input decomposition under the single linear probe (5 seeds)", "",
                  "Generated by `scripts/score/table2_probefix.py` from `results/input_baselines_probefix.json` and",
                  "`results/probefix_matrix_n5.json`. Linear probe (logistic regression, C = 1, max_iter 100000) fitted",
                  "on the first 10,000 training images of each seed's order and scored on the full test set.",
                  "Encoded input: the network's Poisson input spike counts (784-d; 2,312-d for N-MNIST).",
                  "Random: the same network with STDP disabled (pair/triplet share one; voltage-STDP has its own).",
                  "In parentheses: difference from the encoded input (per seed, then averaged); * = same sign in",
                  "all 5 seeds. Mean ± s.d. over seeds 0–4.", "",
                  "| dataset | raw pixels | encoded input | random (pair/triplet) | pair | triplet | random (voltage) | voltage |",
                  "|---|--:|--:|--:|--:|--:|--:|--:|"]
    for ds, name in DS:
        enc = [b[ds]["seeds"][str(s)]["encoded"] for s in SEEDS]
        raw = [b[ds]["seeds"][str(s)]["raw"] for s in SEEDS]
        row = dict(raw=ms(raw), encoded=ms(enc))
        cells = [f(row["raw"]), f(row["encoded"])]
        for key, rule, mode in (("random_pt", "pair_exp", "frozen"), ("pair", "pair_exp", "trained"),
                                ("triplet", "triplet", "trained"), ("random_v", "voltage", "frozen"),
                                ("voltage", "voltage", "trained")):
            acc = [run[(rule, ds, s, mode)] for s in SEEDS]
            d = np.subtract(acc, enc)
            same = bool(np.all(d > 0) or np.all(d < 0))
            row[key] = dict(acc=ms(acc), diff_vs_encoded=ms(d), same_sign=same)
            cells.append(f"{f(ms(acc))} ({np.mean(d):+.1f}{'*' if same else ''})")
        out[ds] = row
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    pos = {r: [n for ds, n in DS if out[ds][r]["diff_vs_encoded"][0] > 0 and out[ds][r]["same_sign"]]
           for r in ("pair", "triplet", "voltage")}
    L += ["", "Trained networks above the encoded input in every seed: "
          + "; ".join(f"{r}: {len(v)} of 8 ({', '.join(v) if v else 'none'})" for r, v in pos.items()) + ".",
          "Random networks above the encoded input on any dataset: "
          + (", ".join(n for ds, n in DS if out[ds]["random_pt"]["diff_vs_encoded"][0] > 0
                       or out[ds]["random_v"]["diff_vs_encoded"][0] > 0) or "none") + "."]
    json.dump(out, open("results/table2_probefix.json", "w"), indent=1)
    open("results/table2_probefix.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
