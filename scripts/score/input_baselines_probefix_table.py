#!/usr/bin/env python3
"""Readable table of results/input_baselines_probefix.json (scripts/score/input_baselines_probefix.py):
the single linear probe applied to each dataset's input instead of a network's output. Nothing is
recomputed; the summary values are re-derived from the per-seed values and checked against the JSON.

Output: results/input_baselines_probefix.md
Usage (repo root): python scripts/score/input_baselines_probefix_table.py
"""
import json
import numpy as np

SRC, OUT = "results/input_baselines_probefix.json", "results/input_baselines_probefix.md"
NAMES = {"mnist": "MNIST", "nmnist": "N-MNIST", "emnist_letters": "EMNIST-Letters", "fmnist": "Fashion-MNIST",
         "organamnist": "OrganAMNIST", "bloodmnist": "BloodMNIST", "tissuemnist": "TissueMNIST", "pathmnist": "PathMNIST"}


def main():
    d = json.load(open(SRC))
    L = ["# Input baselines under the single linear probe", "",
         "Generated by `scripts/score/input_baselines_probefix_table.py` from `results/input_baselines_probefix.json`",
         "(computed by `scripts/score/input_baselines_probefix.py`). Probe: logistic regression, L2, C = 1, raw values,",
         "max_iter 100000, fitted on the first 10,000 training images of each seed's presentation order and scored",
         "on the full test set. Encoded input = input-layer spike counts over the 350 ms of input (Poisson, 63.75 Hz",
         "per unit intensity); raw = the unencoded image vector. Accuracy %, mean ± s.d. over seeds 0-4.", "",
         "| dataset | input size | test images | encoded input | raw pixels | encoded, per seed 0-4 | raw, per seed 0-4 |",
         "|---|--:|--:|--:|--:|---|---|"]
    for k, v in d.items():
        if not isinstance(v, dict):                          # "_protocol" note
            continue
        seeds = sorted(v["seeds"], key=int)
        for key in ("encoded", "raw"):
            vals = [v["seeds"][s][key] for s in seeds]
            m, sd = np.mean(vals), np.std(vals, ddof=1)
            assert abs(m - v[key][0]) < 1e-9 and abs(sd - v[key][1]) < 1e-9, (k, key, m, sd, v[key])
        per = lambda key: ", ".join(f"{v['seeds'][s][key]:.1f}" for s in seeds)
        L.append(f"| {NAMES.get(k, k)} | {v['dim']:,} | {v['n_test']:,} | {v['encoded'][0]:.1f} ± {v['encoded'][1]:.1f} | "
                 f"{v['raw'][0]:.1f} ± {v['raw'][1]:.1f} | {per('encoded')} | {per('raw')} |")
    open(OUT, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
