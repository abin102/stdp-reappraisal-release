def build_workspace(ws):
    """Copy code + shipped results into ws; link run data, logs, features and datasets."""
    def ignore(d, names):
        d = Path(d)
        skip = {"__pycache__", ".git"}
        out = [n for n in names if n in skip]
        for n in names:
            p = d / n
            if p.is_symlink() or (d == REPO / "experiments" and n == "runs"):
                out.append(n)
            elif d == REPO / "results" and (n.startswith("logs_") or n.startswith("conv_feats_")):
                out.append(n)
        return out
    for sub in COPY_DIRS:
        if (REPO / sub).exists():
            shutil.copytree(REPO / sub, ws / sub, ignore=ignore, symlinks=False)
    (ws / "data").mkdir()
    links = []
    for p in sorted((REPO / "data").iterdir()):
        if p.suffix == ".py":
            shutil.copy2(p, ws / "data" / p.name)
        elif p.name != "__pycache__":
            links.append((ws / "data" / p.name, p))
    for p in [REPO / "experiments" / "runs", REPO / "checkpoints"]:
        if p.exists():
            links.append((ws / p.relative_to(REPO), p))
    for p in sorted((REPO / "results").iterdir()):
        if p.name.startswith("logs_") or p.name.startswith("conv_feats_"):
            links.append((ws / "results" / p.name, p))
    for dst, src in links:
        dst.parent.mkdir(parents=True, exist_ok=True)
        os.symlink(src.resolve(), dst)


def order(names):
    seen, out = set(), []
    def visit(n):
        if n in seen:
            return
        seen.add(n)
        for d in TASKS[n][2]:
            visit(d)
        out.append(n)
    for n in names:
        visit(n)
    return out


def run(cmd, ws, log, env_extra=None):
    env = dict(os.environ, PYTHONPATH=str(ws), MPLBACKEND="Agg", **(env_extra or {}))
    t = time.time()
    with open(log, "w") as fh:
        r = subprocess.run([PY] + cmd, cwd=ws, env=env, stdout=fh, stderr=subprocess.STDOUT)
    return r.returncode, time.time() - t


