"""Supervised ceiling (Table A.8) with five seeds, 2026-10-23.

Same data, network and training as scripts/supervised_ceiling.py (greyscale MedMNIST at 28x28,
two-convolution CNN, Adam 1e-3, 15 epochs, batch 256; logistic regression on raw pixels), but the
CNN is trained with torch seeds 0-4 (the original single run set no seed). The logistic regression
is deterministic and is fitted once. The unsupervised column comes from the probe-fix matrix
(results/probefix_matrix_n5.json, pair-STDP, 10,000 training images, five seeds).

Out: results/supervised_ceiling_5seed.{md,json}
Run: CUDA_VISIBLE_DEVICES=k PYTHONPATH=. python scripts/score/supervised_ceiling_5seed.py
"""
import json, random, warnings
from pathlib import Path
import numpy as np
import torch
import torch.nn as nn
from sklearn.linear_model import LogisticRegression
from medmnist import OrganAMNIST, BloodMNIST, TissueMNIST, PathMNIST

from threadpoolctl import threadpool_limits
threadpool_limits(1)   # single-threaded BLAS: probe fits reproduce bit for bit (scripts/score/_blas.py)

warnings.filterwarnings("ignore")
dev = "cuda:0" if torch.cuda.is_available() else "cpu"
SEEDS = range(5)
DSETS = [("OrganA", "organamnist", OrganAMNIST, 11), ("Blood", "bloodmnist", BloodMNIST, 8),
         ("Tissue", "tissuemnist", TissueMNIST, 8), ("Path", "pathmnist", PathMNIST, 9)]


def load(cls):
    tr = cls(split="train", download=True, size=28); te = cls(split="test", download=True, size=28)
    def gray(a):
        a = np.asarray(a, np.float32) / 255.0
        return a.mean(3) if a.ndim == 4 else a          # RGB -> luminance (match STDP greyscale)
    return gray(tr.imgs), tr.labels.ravel().astype(int), gray(te.imgs), te.labels.ravel().astype(int)


class CNN(nn.Module):
    def __init__(self, nc):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(1, 32, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(32, 64, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Flatten(), nn.Linear(64 * 7 * 7, 128), nn.ReLU(), nn.Dropout(0.3), nn.Linear(128, nc))

    def forward(self, x):
        return self.net(x)


def train_cnn(Xtr, ytr, Xte, yte, nc, seed, epochs=15, bs=256):
    torch.manual_seed(seed); np.random.seed(seed); random.seed(seed)
    Xtr_t = torch.tensor(Xtr).unsqueeze(1); ytr_t = torch.tensor(ytr).long()
    Xte_t = torch.tensor(Xte).unsqueeze(1).to(dev); yte_t = torch.tensor(yte).long().to(dev)
    m = CNN(nc).to(dev); opt = torch.optim.Adam(m.parameters(), 1e-3); lf = nn.CrossEntropyLoss()
    n = len(ytr)
    for _ in range(epochs):
        m.train(); perm = torch.randperm(n)
        for i in range(0, n, bs):
            idx = perm[i:i + bs]; opt.zero_grad()
            l = lf(m(Xtr_t[idx].to(dev)), ytr_t[idx].to(dev)); l.backward(); opt.step()
    m.eval(); preds = []
    with torch.no_grad():
        for i in range(0, len(yte_t), 512):
            preds.append(m(Xte_t[i:i + 512]).argmax(1))
    return (torch.cat(preds) == yte_t).float().mean().item() * 100


def main():
    mx = json.load(open("results/probefix_matrix_n5.json"))["cells"]
    res, rows = {}, ["# Supervised ceiling on the medical datasets, five seeds (greyscale, same input as STDP)", "",
                     "Generated by `scripts/score/supervised_ceiling_5seed.py`. Mean ± s.d. over seeds 0-4.", "",
                     "| dataset | chance | unsup-STDP (pair) | sup-linear (raw px) | sup-CNN | sup-CNN per seed |",
                     "|---|--:|--:|--:|--:|---|"]
    for lab, dskey, cls, nc in DSETS:
        Xtr, ytr, Xte, yte = load(cls)
        lin = LogisticRegression(max_iter=100000).fit(Xtr.reshape(len(Xtr), -1), ytr).score(
            Xte.reshape(len(Xte), -1), yte) * 100
        cnn = [train_cnn(Xtr, ytr, Xte, yte, nc, s) for s in SEEDS]
        un = mx[f"pair_exp|{dskey}"]["trained_linear"]
        res[lab] = {"chance": 100.0 / nc, "unsup_stdp_pair": un, "sup_linear": lin,
                    "sup_cnn": [float(np.mean(cnn)), float(np.std(cnn, ddof=1))], "sup_cnn_per_seed": cnn}
        rows.append(f"| {lab} | {100.0 / nc:.1f} | {un[0]:.1f} ± {un[1]:.1f} | {lin:.1f} | "
                    f"{np.mean(cnn):.1f} ± {np.std(cnn, ddof=1):.1f} | {', '.join(f'{v:.1f}' for v in cnn)} |")
        print(rows[-1], flush=True)
    json.dump(res, open("results/supervised_ceiling_5seed.json", "w"), indent=1)
    Path("results/supervised_ceiling_5seed.md").write_text("\n".join(rows) + "\n")
    print("wrote results/supervised_ceiling_5seed.{md,json}")


if __name__ == "__main__":
    main()
