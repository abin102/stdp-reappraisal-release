#!/usr/bin/env python3
"""Regenerate every result table shipped in results/ from the saved runs and compare it with the
shipped copy. Optionally regenerate the paper's figures and compare them with a reference folder.

How it works
  A scratch copy of the code (models/, experiments/ without runs, conv/, data/*.py, scripts/,
  run_configs/) and of results/ is made in a temporary folder; the large inputs are linked into it
  (see Inputs). Each scorer's own outputs are deleted from the copy and the scorer is run there,
  in dependency order, so a table that reads another table reads the regenerated one. Nothing in
  the repository is written. Comparison: .md / .csv / .txt byte for byte; .json same key sets
  everywhere and numbers equal to 1e-9 (absolute or relative); .pdf byte for byte.

Inputs (relative to the repository root; regenerate them with the launchers in scripts/train/ and
scripts/extract/, see RUN_MAP.md and run_configs/INDEX.md)
  experiments/runs/          every run directory the paper uses (config.yaml, metrics.json,
                             weights_final.npz, {train,test}_spike_counts[_pf].npz, ...), including
                             experiments/runs/clopath_port/{grid10k,explore_k0,thetatar10k,...}
  results/logs_conv5/        readout logs of the 5-seed conv surrogate runs
                             (conv_surrogate_readout_n5.py)
  results/conv_feats_pairN5_{trained,random}_s{0-4}.npz
                             pooled conv features of the pair-STDP conv control
                             (scripts/extract/extract_pair_feats.py; conv_pair_n5_table.py)
  data/                      the eight datasets (downloaded by run_single.py / medmnist_loader.py);
                             only input_baselines_probefix.py and identical_neuron_check.py read them
  CLOPATH_MODELDB_DIR        (environment, optional) Clopath's ModelDB files; only the Section 4.4
                             mechanism figure needs them; without it that figure is reported SKIP
  Missing inputs make the affected table FAIL with the scorer's own message; nothing is guessed.

Exactness. The linear probes are L-BFGS fits on raw spike counts, fitted to convergence
(max_iter 100000). These fits are badly conditioned, so where they stop depends on the order of
floating-point sums. Every fit therefore runs with one BLAS thread (scripts/score/_blas.py), and the
shipped tables were made that way, with numpy 1.26.4 / OpenBLAS 0.3.23 and scikit-learn 1.6.1.
With the same versions, expect identical tables. With another BLAS build, a fit can move by about one
test image. Setting OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 as well is recommended.
GPU: clopath_port_validate.py runs on cuda:0 when one is visible (the shipped file was made on a
GPU). Set CUDA_VISIBLE_DEVICES="" to run everything on the CPU; the device and wall-clock entries
of validation.json are not compared (see VOLATILE).

Not regenerated here (they need a GPU simulation or network training, not just scoring):
  conv_svm_{trained,random}_s*.json, gate_scaffold_seed*.json, gate_probes_2026-10/*.json,
  voltage_plateau_gate_probe/*.json, clopath_port_calibration/calibration.json,
  supervised_ceiling_5seed.{md,json}; clopath_port_validation/equivalence.json needs GNU Octave
  and the ModelDB files (run scripts/checks/clopath_port_equivalence.py by hand);
  clopath_port_thetatar/check_*.json are the checks made before the homeostatic-reference sweep
  (scripts/train/clopath_port_thetatar_sweep.sh requires check_default_reproduction.json).
Documents (not generated by code): *_PREREG.md, clopath_positive_control.md, run_lists/,
  gate_probes_2026-10/*.yaml.

Usage (repo root):
  OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 PYTHONPATH=. \
      python scripts/checks/check_results.py --jobs 8 --workspace DIR --resume   # all tables (CPU hours)
  PYTHONPATH=. python scripts/checks/check_results.py --only table2_probefix probefix_aggregate
  PYTHONPATH=. python scripts/checks/check_results.py --figures REF_DIR   # also figures vs REF_DIR
  options: --list, --keep (keep the scratch folder), --jobs N (scorers run in parallel),
           --workspace DIR (scratch folder that is kept), --resume (with --workspace: skip scorers that
           finished there; each finished scorer leaves _logs/<name>.done)
Exit status 0 if nothing FAILed.
"""
