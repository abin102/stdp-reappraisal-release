#!/usr/bin/env python3
"""Table 3 "architecture" row: logistic regression on the pooled features of the two-layer
convolutional voltage-STDP network, trained vs random (untrained) filters, seeds 1-5.

Inputs: results/conv_svm_{trained,random}_s{1..5}.json, written by scripts/extract/conv_svm_readout.py
(field "logreg": test accuracy in %, 12,000 training and 10,000 test images).
Gap = trained - random of the same seed; mean and sample s.d. (ddof=1) over seeds.
Usage (repo root): PYTHONPATH=. python scripts/score/conv_arch_logreg_n5.py [--seeds 1 2 3 4 5]
Out: results/conv_arch_logreg_n5.json, results/conv_arch_logreg_n5.md
"""
import argparse
import json

import numpy as np

OUT = "results/conv_arch_logreg_n5"


def ms(x):
    return float(np.mean(x)), float(np.std(x, ddof=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3, 4, 5])
    ap.add_argument("--dir", default="results", help="folder with conv_svm_*_s*.json")
    args = ap.parse_args()
    acc = {k: [json.load(open(f"{args.dir}/conv_svm_{k}_s{s}.json"))["logreg"] for s in args.seeds]
           for k in ("trained", "random")}
    gap = [t - r for t, r in zip(acc["trained"], acc["random"])]
    out = dict(seeds=args.seeds, trained=acc["trained"], random=acc["random"], gap=gap,
               trained_mean_sd=ms(acc["trained"]), random_mean_sd=ms(acc["random"]), gap_mean_sd=ms(gap),
               trained_below_random=int(sum(g < 0 for g in gap)))
    json.dump(out, open(OUT + ".json", "w"), indent=1)
    f = lambda m: f"{m[0]:.1f} ± {m[1]:.1f}"
    L = ["# Table 3 architecture row: logistic regression on pooled convolutional features", "",
         "Generated by `scripts/score/conv_arch_logreg_n5.py` from results/conv_svm_{trained,random}_s*.json.", "",
         "| seed | trained | random | gap |", "|--:|--:|--:|--:|"]
    L += [f"| {s} | {t:.2f} | {r:.2f} | {g:+.2f} |" for s, t, r, g in zip(args.seeds, acc["trained"], acc["random"], gap)]
    L += [f"| mean ± s.d. | {f(out['trained_mean_sd'])} | {f(out['random_mean_sd'])} | {f(out['gap_mean_sd'])} |", "",
          f"Trained below random in {out['trained_below_random']} of {len(gap)} seeds."]
    open(OUT + ".md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
